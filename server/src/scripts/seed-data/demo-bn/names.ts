/**
 * Demo-school name pools ([58.1.04], D5 / D25). Every name here is an
 * invented combination of common given names and surnames; none is meant to
 * point at a real person. Each entry is `{ en, bn }`: `en` is ASCII, `bn` is
 * the same name in Bengali script.
 *
 * Pools are written as compact `'English|বাংলা'` strings and split once at
 * load time, to keep this file reviewable.
 */

export interface NamePair {
  en: string;
  bn: string;
}

export type NameGroup = 'MUSLIM' | 'HINDU' | 'BUDDHIST' | 'CHRISTIAN' | 'CHAKMA' | 'MARMA';

export interface NamePool {
  boys: readonly NamePair[];
  girls: readonly NamePair[];
  surnames: readonly NamePair[];
}

